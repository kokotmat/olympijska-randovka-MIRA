import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../functions/api/scanner.js',import.meta.url),'utf8');
const {onRequest}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const originalFetch=globalThis.fetch;
const request=(data,options={})=>new Request('https://example.com/api/scanner',{method:'POST',headers:{Origin:'https://example.com',...options.headers},body:JSON.stringify(data),...options});
let calls=0;
globalThis.fetch=async()=>{calls++;throw new Error('Unexpected upstream access');};
assert.equal((await onRequest({request:new Request('https://example.com/api/scanner')})).status,405);
assert.equal((await onRequest({request:request({action:'scannerLogin',pin:'test'},{headers:{Origin:'https://other.example'}})})).status,403);
assert.equal((await onRequest({request:request({action:'reservation',email:'test@example.invalid'})})).status,400);
assert.equal((await onRequest({request:request({action:'scannerLogin',pin:'x'.repeat(5000)})})).status,413);
assert.equal((await onRequest({request:request({action:'scan',hash:'bad',session:'fake'})})).status,400);
assert.equal(calls,0);
globalThis.fetch=async(url,options)=>{
  assert.match(url,/^https:\/\/script\.google\.com\/macros\/s\/[\w-]+\/exec$/);
  assert.deepEqual(JSON.parse(options.body),{action:'scannerLogin',pin:'test-only-invalid'});
  return Response.json({status:'error',message:'Nesprávný PIN.'});
};
const login=await onRequest({request:request({action:'scannerLogin',pin:'test-only-invalid',endpoint:'https://attacker.invalid',count:10})});
assert.equal(login.status,200);assert.equal(login.headers.get('Cache-Control'),'no-store');
assert.equal((await login.json()).message,'Nesprávný PIN.');
globalThis.fetch=async()=>Response.json({status:'error',code:'USED',title:'JIŽ POUŽITO'});
const scan=await onRequest({request:request({action:'scan',hash:'abcdef01-1234-5678-90ab-abcdefabcdef',session:'fake-test-session'})});
assert.equal((await scan.json()).code,'USED');
globalThis.fetch=async()=>new Response('<html>Sign in</html>');
assert.equal((await onRequest({request:request({action:'scannerLogin',pin:'test'})})).status,502);
globalThis.fetch=async()=>new Response('Unavailable',{status:503});
assert.equal((await onRequest({request:request({action:'scannerLogin',pin:'test'})})).status,502);
globalThis.fetch=originalFetch;
console.log('PASS: scanner gateway origin, method, payload limit, operation whitelist, fixed upstream, field filtering, readable errors, no-cache and no false admission.');
